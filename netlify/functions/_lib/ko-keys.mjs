export const hasHangul = s => /[ㄱ-ㆎ가-힣]/.test(String(s || ''));
export function koToQwerty(s) {
  let out = '';
  for (const ch of String(s || '')) {
    const c = ch.charCodeAt(0);
    if (c >= 0xac00 && c <= 0xd7a3) {
      const i = c - 0xac00;
      out += KEY[CHO[Math.floor(i / 588)]] + KEY[JUNG[Math.floor((i % 588) / 28)]] + (KEY[JONG[i % 28]] || '');
    } else out += KEY[ch] || ch;
  }
  return out;
}
// 대문자 잠금(Caps Lock)이 켜진 채 친 글자
export const swapCase = s => String(s || '').replace(/[a-zA-Z]/g, c => (c === c.toLowerCase() ? c.toUpperCase() : c.toLowerCase()));
